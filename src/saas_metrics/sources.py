"""docs/sources.md (MongoDB; config.SOURCES in general): every SEC filing used, with accession numbers."""
from __future__ import annotations

import duckdb

from saas_metrics import config, model

EDGAR = "https://www.sec.gov/Archives/edgar/data/{cik}/{folder}/"


def render(con: duckdb.DuckDBPyConnection) -> str:
    fl = con.execute("SELECT form, period_end, filed, accn FROM filings ORDER BY period_end").df()
    gk = con.execute("""SELECT DISTINCT accn, filed, issued, known_at_cutoff FROM guidance
                        ORDER BY filed""").df()
    lines = [
        "# Sources",
        "",
        f"All data comes from {config.ACTIVE.name} (CIK {config.CIK}) filings on SEC EDGAR. This page is generated by",
        "`saas-metrics sources` from the local store; a test keeps it in sync.",
        "",
        f"Forecast cutoff: **{config.CUTOFF_DATE}**. Filings dated after it are used only to score the forecast.",
        "",
        "## Quarterly and annual reports (10-Q, 10-K)",
        "",
        "XBRL instance documents for the financial statements; filing text for the operating KPIs",
        f"({', '.join(k['name'] for k in config.ACTIVE.raw.get('kpis', []))}).",
        "",
        "| Form | Fiscal period | Period end | Filed | Accession | Used for the forecast |",
        "|---|---|---|---|---|---|",
    ]
    for r in fl.itertuples():
        url = EDGAR.format(cik=config.CIK, folder=r.accn.replace("-", ""))
        used = "yes" if r.filed <= config.CUTOFF_DATE else "scoring only"
        period = model.periods.label(r.period_end)
        period = period.split()[1] if r.form == "10-K" else period
        lines.append(f"| {r.form} | {period} | {r.period_end} | {r.filed} | "
                     f"[{r.accn}]({url}) | {used} |")
    lines += [
        "",
        "## Earnings releases (8-K, exhibit 99.1)",
        "",
        "Management guidance (next quarter and full year) and company-defined non-GAAP results.",
        "",
        "| Filed | Guidance issued | Accession | Known at the cutoff |",
        "|---|---|---|---|",
    ]
    for r in gk.itertuples():
        url = EDGAR.format(cik=config.CIK, folder=r.accn.replace("-", ""))
        lines.append(f"| {r.filed} | {r.issued} | [{r.accn}]({url}) | {'yes' if r.known_at_cutoff else 'no'} |")
    lines += ["", "SEC's companyfacts API is used only as an independent cross-check of the parsed values.", ""]
    return "\n".join(lines)


def write(con: duckdb.DuckDBPyConnection) -> str:
    config.SOURCES.parent.mkdir(parents=True, exist_ok=True)
    config.SOURCES.write_text(render(con))
    return str(config.SOURCES)
